const setLanguage = (lang) => {
    const strings = translations[lang] || translations.es;
    document.title = strings.title;
    document.documentElement.lang = lang;
    document.querySelector('meta[name="description"]')?.setAttribute("content", strings.meta_description);
    document.querySelector('meta[property="og:locale"]')?.setAttribute("content", strings.og_locale);
    document.querySelector('meta[property="og:title"]')?.setAttribute("content", strings.title);
    document.querySelector('meta[property="og:description"]')?.setAttribute("content", strings.meta_description);
    document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", strings.title);
    document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", strings.meta_description);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (strings[key]) {
            const nextText = strings[key];
            const card = el.closest("[data-type-card]");
            if (card && card.dataset.typed !== "true") {
                el.dataset.typewriterSource = nextText;
                el.textContent = "";
            } else {
                delete el.dataset.typewriterSource;
                el.textContent = nextText;
            }
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
        const key = el.getAttribute("data-i18n-html");
        if (strings[key]) {
            el.innerHTML = strings[key];
        }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
        const key = el.getAttribute("data-i18n-aria");
        if (strings[key]) {
            el.setAttribute("aria-label", strings[key]);
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (strings[key]) {
            el.setAttribute("placeholder", strings[key]);
        }
    });

    updateReadToggleLabels(strings);

    document.querySelectorAll("[data-lang]").forEach((button) => {
        const active = button.getAttribute("data-lang") === lang;
        button.classList.toggle("bg-white/10", active);
        button.classList.toggle("text-white", active);
    });
};

const updateReadToggleLabels = (strings) => {
    document.querySelectorAll("[data-read-toggle]").forEach((button) => {
        const expanded = button.getAttribute("aria-expanded") === "true";
        button.textContent = expanded ? strings.read_less : strings.read_more;
    });
};

const toggleBioText = (button) => {
    const bioId = button.getAttribute("data-target");
    if (!bioId) return;

    const bioElement = document.getElementById(bioId);
    if (!bioElement) return;

    const isExpanded = button.getAttribute("aria-expanded") === "true";
    bioElement.classList.toggle("line-clamp-4", isExpanded);

    const nextExpanded = !isExpanded;
    button.setAttribute("aria-expanded", nextExpanded ? "true" : "false");
    button.dataset.expanded = nextExpanded ? "true" : "false";

    const lang = localStorage.getItem("lang") || "es";
    const strings = translations[lang] || translations.es;
    button.textContent = nextExpanded ? strings.read_less : strings.read_more;
};

