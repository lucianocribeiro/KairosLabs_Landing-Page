const mobileMenuBtn = document.getElementById("mobile-menu-btn");
const mobileMenu = document.getElementById("mobile-menu");
const mobileLinks = document.querySelectorAll(".mobile-link");
let menuOpen = false;

const toggleMenu = (forceState) => {
    if (!mobileMenuBtn || !mobileMenu) return;

    menuOpen = typeof forceState === "boolean" ? forceState : !menuOpen;
    mobileMenu.classList.toggle("translate-x-full", !menuOpen);
    document.body.classList.toggle("mobile-menu-open", menuOpen);
    mobileMenuBtn.setAttribute("aria-expanded", menuOpen ? "true" : "false");
    mobileMenuBtn.innerHTML = menuOpen
        ? '<i data-lucide="x" class="w-7 h-7"></i>'
        : '<i data-lucide="menu" class="w-7 h-7"></i>';
    lucide.createIcons();
};

mobileMenuBtn?.addEventListener("click", () => toggleMenu());
mobileLinks.forEach((link) => {
    link.addEventListener("click", () => {
        if (menuOpen) toggleMenu(false);
    });
});
window.addEventListener("resize", () => {
    if (window.innerWidth >= 1024 && menuOpen) {
        toggleMenu(false);
    }
});
window.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && menuOpen) {
        toggleMenu(false);
    }
});

const revealElements = document.querySelectorAll(".reveal");
const typedElements = new WeakSet();

const typeText = (element, speed = 16) => {
    if (!element || typedElements.has(element)) return Promise.resolve();

    const sourceText = element.dataset.typewriterSource || element.textContent || "";
    if (!sourceText.trim()) {
        typedElements.add(element);
        return Promise.resolve();
    }

    typedElements.add(element);
    element.classList.add("is-typing");
    element.textContent = "";

    return new Promise((resolve) => {
        let index = 0;
        const tick = () => {
            index += 1;
            element.textContent = sourceText.slice(0, index);
            if (index < sourceText.length) {
                window.setTimeout(tick, speed);
            } else {
                delete element.dataset.typewriterSource;
                element.classList.remove("is-typing");
                resolve();
            }
        };
        tick();
    });
};

const typeCardContent = async (card) => {
    if (!card || card.dataset.typed === "true") return;
    card.dataset.typed = "true";

    const targets = card.querySelectorAll("h2[data-i18n], h3[data-i18n], h4[data-i18n], p[data-i18n]");
    for (const target of targets) {
        await typeText(target, 18);
        await new Promise((resolve) => window.setTimeout(resolve, 90));
    }
};

const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
        if (entry.isIntersecting) {
            entry.target.classList.add("active");
            if (entry.target.matches("[data-type-card]")) {
                typeCardContent(entry.target);
            }
            observer.unobserve(entry.target);
        }
    });
}, {
    root: null,
    threshold: 0.12,
    rootMargin: "0px 0px -50px 0px"
});
revealElements.forEach((element) => revealObserver.observe(element));

const contactForm = document.getElementById("contact-form");
const contactSubmitButton = document.getElementById("contact-submit");
const contactStatus = document.getElementById("contact-status");
const CONTACT_WEBHOOK_URL =
    contactForm?.dataset.webhookUrl ||
    window.KAIROS_CONTACT_WEBHOOK_URL ||
    "";

const postViaHiddenForm = (url, payload) => {
    const iframeName = `webhook-target-${Date.now()}`;
    const iframe = document.createElement("iframe");
    iframe.name = iframeName;
    iframe.style.display = "none";
    document.body.appendChild(iframe);

    const form = document.createElement("form");
    form.method = "POST";
    form.action = url;
    form.target = iframeName;
    form.style.display = "none";

    Object.entries(payload).forEach(([key, value]) => {
        const input = document.createElement("input");
        input.type = "hidden";
        input.name = key;
        input.value = value ?? "";
        form.appendChild(input);
    });

    document.body.appendChild(form);
    form.submit();

    setTimeout(() => {
        form.remove();
        iframe.remove();
    }, 3000);
};

contactForm?.addEventListener("submit", async (event) => {
    event.preventDefault();

    const lang = localStorage.getItem("lang") || "es";
    const strings = translations[lang] || translations.es;

    if (!CONTACT_WEBHOOK_URL) {
        contactStatus.textContent = strings.footer_form_missing_webhook;
        contactStatus.classList.remove("text-sky-400");
        contactStatus.classList.add("text-red-400");
        return;
    }

    const formData = new FormData(contactForm);
    const payload = {
        Nombre: formData.get("name"),
        Email: formData.get("email"),
        Mensaje: formData.get("message")
    };

    contactSubmitButton.disabled = true;
    contactStatus.textContent = strings.footer_form_submitting;
    contactStatus.classList.remove("text-red-400");
    contactStatus.classList.add("text-sky-400");

    try {
        const response = await fetch(CONTACT_WEBHOOK_URL, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify(payload)
        });

        if (!response.ok) {
            throw new Error("Webhook request failed");
        }

        contactForm.reset();
        contactStatus.textContent = strings.footer_form_success;
    } catch (error) {
        try {
            // Fallback for webhook endpoints that do not expose CORS headers.
            await fetch(CONTACT_WEBHOOK_URL, {
                method: "POST",
                mode: "no-cors",
                headers: {
                    "Content-Type": "text/plain;charset=UTF-8"
                },
                body: JSON.stringify(payload)
            });

            contactForm.reset();
            contactStatus.textContent = strings.footer_form_success;
            contactStatus.classList.remove("text-red-400");
            contactStatus.classList.add("text-sky-400");
        } catch (fallbackError) {
            try {
                postViaHiddenForm(CONTACT_WEBHOOK_URL, payload);
                contactForm.reset();
                contactStatus.textContent = strings.footer_form_success;
                contactStatus.classList.remove("text-red-400");
                contactStatus.classList.add("text-sky-400");
            } catch (formError) {
                console.error(error);
                console.error(fallbackError);
                console.error(formError);
                contactStatus.textContent = strings.footer_form_error;
                contactStatus.classList.remove("text-sky-400");
                contactStatus.classList.add("text-red-400");
            }
        }
    } finally {
        contactSubmitButton.disabled = false;
    }
});

